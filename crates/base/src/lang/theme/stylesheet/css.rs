#[cfg(not(feature = "std"))]
use std::prelude::v1::*;

use super::defaults::get_default_tokens;
use super::tokens::{generate_tokens_css, generate_tokens_css_dark};
use crate::schema::ThemeDefinition;

/// Generate CSS custom properties from a theme definition
///
/// Uses the unified theme system with `data-theme="name-light"` and `data-theme="name-dark"` selectors.
/// The ThemeProvider sets this attribute on the document element.
///
/// Generates:
/// - Light mode: `[data-theme="name-light"]` with complete variables
/// - Dark mode: `[data-theme="name-dark"]` with complete variables
pub fn generate_theme_css(theme: &ThemeDefinition) -> String {
    let mut css = String::new();
    let defaults = get_default_tokens();

    // Add header comment
    css.push_str(&format!(
        "/**\n * Theme: {}\n * Generated by Orbital Compiler\n */\n\n",
        theme.name
    ));

    // Generate light mode with complete variables
    css.push_str("/* ==========================================================================\n");
    css.push_str(" * LIGHT MODE\n");
    css.push_str(
        " * ========================================================================== */\n",
    );
    css.push_str(&format!("[data-theme=\"{}-light\"] {{\n", theme.name));
    css.push_str(&generate_tokens_css(&theme.tokens, "  ", &defaults, false));
    css.push_str("}\n");

    // Generate dark mode with complete variables
    css.push('\n');
    css.push_str("/* ==========================================================================\n");
    css.push_str(" * DARK MODE\n");
    css.push_str(
        " * ========================================================================== */\n",
    );
    css.push_str(&format!("[data-theme=\"{}-dark\"] {{\n", theme.name));

    // Start with light mode tokens, then overlay dark mode overrides
    let dark_variant = theme.variants.as_ref().and_then(|v| v.get("dark"));
    css.push_str(&generate_tokens_css_dark(
        &theme.tokens,
        dark_variant,
        "  ",
        &defaults,
    ));
    css.push_str("}\n");

    css
}

/// Every distinct `typeScale.fontImport` URL across `themes` (base tokens and
/// every variant), sorted. The app stylesheet emits them as leading
/// `@import url(…)` rules — `@import` must precede every other rule, so they
/// can't live inside the per-theme files that the app stylesheet inlines.
pub fn theme_font_imports(themes: &[ThemeDefinition]) -> Vec<String> {
    let mut urls: Vec<String> = Vec::new();
    for theme in themes {
        let variant_scales = theme
            .variants
            .iter()
            .flat_map(|v| v.values())
            .filter_map(|v| v.type_scale.as_ref());
        for ts in theme.tokens.type_scale.iter().chain(variant_scales) {
            if let Some(url) = &ts.font_import {
                if !urls.contains(url) {
                    urls.push(url.clone());
                }
            }
        }
    }
    urls.sort();
    urls
}

/// The themes a program paints: the declared ones, or the installed default preset when it declares none.
/// Its `themes.css` and the client's theme list are both these, so the client applies a theme the sheet defines.
pub fn program_themes(declared: &[ThemeDefinition]) -> Vec<ThemeDefinition> {
    if !declared.is_empty() {
        return declared.to_vec();
    }
    crate::theme::ThemePresets::installed()
        .get(crate::theme::DEFAULT_THEME_BASE)
        .cloned()
        .into_iter()
        .collect()
}

/// A program's `themes.css`: [`program_themes`] with their font imports first. Every host paints this one stylesheet.
pub fn program_themes_css(declared: &[ThemeDefinition]) -> String {
    let styled = program_themes(declared);
    let mut css = String::new();
    for url in theme_font_imports(&styled) {
        css.push_str(&format!("@import url(\"{url}\");\n"));
    }
    for theme in &styled {
        css.push_str(&generate_theme_css(theme));
        css.push('\n');
    }
    css
}
