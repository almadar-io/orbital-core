use ts_rs::{Config, TypeVisitor, TS};

/// Declares a type whose TypeScript form is written here: `$name` is its exported name and
/// `$decl` its right-hand side.
macro_rules! declared_by_hand {
    ($ty:ty, $name:literal, $decl:literal $(, [$($dep:ty),*])?) => {
        impl TS for $ty {
            type WithoutGenerics = Self;
            type OptionInnerType = Self;
            fn name(_: &Config) -> String {
                $name.to_string()
            }
            fn inline(_: &Config) -> String {
                $name.to_string()
            }
            fn decl(_: &Config) -> String {
                format!("type {} = {}", $name, $decl)
            }
            fn decl_concrete(cfg: &Config) -> String {
                <Self as TS>::decl(cfg)
            }
            fn output_path() -> Option<PathBuf> {
                Some(PathBuf::from(concat!($name, ".ts")))
            }
            fn visit_dependencies(_v: &mut impl TypeVisitor)
            where
                Self: 'static,
            {
                $($(_v.visit::<$dep>();)*)?
            }
        }
    };
}
declared_by_hand!(
    TraitSnapshot,
    "TraitSnapshot",
    "{ state: string, entity: JsonValue }"
);
declared_by_hand!(
    AwaitingTrait,
    "AwaitingTrait",
    "{ trait: string, event: string, from: string }"
);
declared_by_hand!(CanvasTheme, "CanvasTheme", "JsonObject");
declared_by_hand!(ResolvedMotion, "ResolvedMotion", "JsonObject");

struct Collect<'a> {
    cfg: &'a Config,
    seen: Vec<TypeId>,
    decls: BTreeMap<String, String>,
}

impl TypeVisitor for Collect<'_> {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if T::output_path().is_some() {
            if self.seen.contains(&TypeId::of::<T>()) {
                return;
            }
            self.seen.push(TypeId::of::<T>());
            self.decls.insert(T::ident(self.cfg), T::decl(self.cfg));
        }
        T::visit_dependencies(self);
        T::visit_generics(self);
    }
}

fn kernel_wire_ts() -> String {
    let cfg = Config::new().with_large_int("number");
    let mut collect = Collect {
        cfg: &cfg,
        seen: Vec::new(),
        decls: BTreeMap::new(),
    };
    collect.visit::<DispatchWire>();
    collect.visit::<AppliedWire>();
    collect.visit::<MountWire>();
    collect.visit::<FrameWire>();
    collect.visit::<SnapshotWire>();
    collect.visit::<ServerProgressWire>();
    collect.visit::<ResolveProgressWire>();
    collect.visit::<IoReplyWire>();
    collect.visit::<EventRequest>();
    collect.visit::<EventResponse>();
    collect.visit::<QueryCapabilities>();
    collect.visit::<WriteCapabilities>();
    collect.visit::<RowSetRef>();

    let mut out = String::from(
        "// GENERATED by `cargo test -p orbital-core kernel_wire_ts` (KERNEL_WIRE_TS_WRITE=1) from\n\
         // orbital-core `embed::wire`. Do not edit: change the Rust wire types and regenerate.\n\n\
         import type {\n  EntityRow,\n  EventId,\n  FieldValue,\n  EventPayload,\n  EventPayloadValue,\n  JsonObject,\n  JsonValue,\n  NamespacedEffectName,\n  OrbitalId,\n  PatternConfig,\n  RawUserClaims,\n  ResolvedPatternProps,\n  ServerBatchSummary,\n  TraitId,\n} from '../types/index.js';\n\n",
    );
    for decl in collect.decls.values() {
        out.push_str("export ");
        out.push_str(decl);
        out.push_str("\n\n");
    }
    out.truncate(out.trim_end().len());
    out.push('\n');
    out
}

fn committed_path() -> PathBuf {
    PathBuf::from(concat!(env!("CARGO_MANIFEST_DIR"), "/../.."))
        .join("../../../packages/almadar-core/src/generated/kernel-wire.ts")
}

#[test]
fn kernel_wire_ts_is_current() {
    let generated = kernel_wire_ts();
    let path = committed_path();
    if std::env::var("KERNEL_WIRE_TS_WRITE").as_deref() == Ok("1") {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, &generated).unwrap();
        return;
    }
    match std::fs::read_to_string(&path) {
        Ok(committed) => assert_eq!(
            committed, generated,
            "kernel-wire.ts is stale: KERNEL_WIRE_TS_WRITE=1 cargo test -p orbital-core kernel_wire_ts"
        ),
        Err(_) => assert!(
            !path.parent().unwrap().exists(),
            "kernel-wire.ts is missing: KERNEL_WIRE_TS_WRITE=1 cargo test -p orbital-core kernel_wire_ts"
        ),
    }
}

#[test]
fn every_wire_type_is_declared() {
    let ts = kernel_wire_ts();
    for name in [
        "DispatchWire",
        "RoutedLeg",
        "SeedWire",
        "AppliedWire",
        "MountWire",
        "MountLegWire",
        "MountFailure",
        "StatefulLegWire",
        "FrameWire",
        "FiredTick",
        "FrameDispatch",
        "SnapshotWire",
        "AmbiguousTrait",
        "ServerProgressWire",
        "ResolveProgressWire",
        "PendingRequestWire",
        "IoRequestWire",
        "IoReplyWire",
        "IoAnswerWire",
        "CallerWire",
        "CallSiteWire",
        "HttpBody",
        "HttpRequestWire",
        "HttpResponseWire",
        "HttpFailureWire",
        "StreamFramingWire",
        "CallRoutesWire",
        "SubstrateFailureWire",
        "EventRequest",
        "EventResponse",
        "ClientEffect",
        "ClientEffectByTrait",
        "RepaintReason",
        "EmittedEvent",
        "BusEventSource",
        "ServerEffectResult",
        "TransitionRejection",
        "DeliveryRecord",
        "DispatchLog",
        "MountSeed",
        "TraitSnapshot",
        "AwaitingTrait",
        "DispatchMode",
        "NavigateOptions",
        "RowPredicate",
        "QueryCapabilities",
        "WriteCapabilities",
        "RowSetRef",
        "RowPage",
        "RowIdPage",
        "RowWriteOutcome",
    ] {
        assert!(
            ts.contains(&format!("export type {name} = ")),
            "{name} missing from the generated mirror"
        );
    }
    assert!(ts.contains("export type Settled<T, E> = "));
    assert!(!ts.contains("bigint"));
}
